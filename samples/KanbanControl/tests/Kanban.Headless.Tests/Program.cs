using Avalonia;
using Avalonia.Controls;
using Avalonia.Controls.Templates;
using Avalonia.Headless;
using Avalonia.Threading;
using Avalonia.VisualTree;
using Kanban.Avalonia;
using Kanban.Core;
using Kanban.Sample;

AppBuilder.Configure<App>().UseHeadless(new AvaloniaHeadlessPlatformOptions { UseHeadlessDrawing = true }).SetupWithoutStarting();
var view = new MainView();
var window = new Window { Width = 1440, Height = 960, Content = view };
window.Show();
int checks = 0;
void Pump() { for (int i = 0; i < 4; i++) { Dispatcher.UIThread.RunJobs(); window.Measure(new Size(1440, 960)); window.Arrange(new Rect(0, 0, 1440, 960)); } }
void Check(bool value, string name) { checks++; if (!value) throw new Exception(name); Console.WriteLine($"PASS {name}"); }
Pump(); var board = view.BoardControl;
Check(board.Controller.Diagnostics.Count == 0, "valid sample data");
Check(board.Rows.Count == 1 && board.Rows[0].Columns.Count == 4, "four templated columns");
Check(board.GetVisualDescendants().OfType<KanbanColumn>().Count() == 4, "column templates realized");
Check(board.GetVisualDescendants().OfType<KanbanCard>().Any(), "custom card containers realized");
Check(board.GetVisualDescendants().OfType<KanbanListBox>().All(l => l.ItemsPanel is not null), "replaceable items panels");
board.SelectOnly(view.Items[0]); Pump();
Check(board.SelectedItems.Count == 1 && ReferenceEquals(board.SelectedItem, view.Items[0]), "two-way selection");
Check(board.GetVisualDescendants().OfType<KanbanCard>().Any(c => c.IsSelected && ReferenceEquals(c.Content, view.Items[0])), "visual selection synchronized");
Check(board.MoveSelection(1).Succeeded, "keyboard command move path"); Pump();
Check(view.Items[0].ColumnKey == "doing", "source placement updated");
Check(board.Undo().Succeeded, "undo control API"); Pump();
board.SearchText = "onboarding"; Pump();
Check(board.VisibleCount == 1, "search projection");
Check(board.Controller.GetColumnCount("backlog") == 4, "filter does not change WIP counts");
board.SearchText = "no matches at all"; Pump();
Check(board.VisibleCount == 0 && board.Rows[0].Columns.All(c => c.IsEmpty), "empty templates");
board.SearchText = ""; Pump();
board.Filter = o => ((WorkItem)o).IsLocked; Pump(); Check(board.VisibleCount == 1, "custom predicate");
board.Filter = null;
board.SortComparer = Comparer<object>.Create((a,b) => StringComparer.Ordinal.Compare(((WorkItem)a).Title, ((WorkItem)b).Title)); Pump();
Check(!board.MoveSelection(0,1).Succeeded, "manual ordering disabled during sort");
board.SortComparer = null;
view.SetSwimlanes(true); Pump();
Check(board.Rows.Count == 2 && board.GetVisualDescendants().OfType<KanbanColumn>().Count() == 8, "swimlanes rendered");
board.Swimlanes[0].IsCollapsed = true; Pump(); Check(!board.Rows[0].IsExpanded, "swimlane collapse");
board.Columns[0].IsCollapsed = true; Pump(); Check(board.Rows.All(r => r.Columns[0].DisplayWidth == 64), "column collapse across lanes");
board.Columns[0].IsCollapsed = false; board.Columns[0].Width = 340; Pump(); Check(board.Rows.All(r => r.Columns[0].DisplayWidth == 340), "column resize across lanes");
view.SetDark(true); Pump(); Check(Application.Current!.RequestedThemeVariant == global::Avalonia.Styling.ThemeVariant.Dark, "dark theme applied");
view.SetCompact(true); Pump(); Check(board.Classes.Contains("compact"), "compact class");
view.Reset(10_000); Pump();
int rendered = board.GetVisualDescendants().OfType<KanbanCard>().Count();
Check(board.Controller.Entries.Count == 10_000 && board.VisibleCount == 10_000, "10k data projection");
Check(rendered > 0 && rendered < 160, $"card virtualization bounded ({rendered} realized for 10k)");
view.Reset(); Pump(); var json = view.ExportJson();
view.Items.RemoveAt(0); view.ImportJson(json); Pump(); Check(view.Items.Count == 16 && view.Items[0].Id == "ATL-101", "JSON round trip");
var before = view.ExportJson(); bool invalid = false; try { view.ImportJson("{\"SchemaVersion\":42}"); } catch(ArgumentException) { invalid = true; }
Check(invalid && before == view.ExportJson(), "invalid import leaves source untouched");
var columns = board.GetVisualDescendants().OfType<KanbanColumn>().ToArray();
columns[0].Template = new FuncControlTemplate<KanbanColumn>((_,_) => new Border()); Pump();
Check(board.Controller.Entries.Count == 16, "column template may omit optional parts");
board.Template = new FuncControlTemplate<KanbanBoard>((_,_) => new Border()); Pump();
Check(board.Move(new(["ATL-101"], "done")).Succeeded, "logic independent of missing visual parts");
window.Content = null; Pump(); Check(board.Controller.Entries.Count == 0, "detach releases controller subscriptions");
window.Content = view; Pump(); Check(board.Controller.Entries.Count == 16, "reattach restores source subscription");
window.Close();
Console.WriteLine($"RESULT: {checks} headless assertions passed.");
